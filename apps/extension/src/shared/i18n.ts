export type Language = "en" | "zh";
export const STRINGS: Record<Language, Strings> = { en, zh };
export type ExtensionStrings = Strings;

export function strings(language: Language | undefined): Strings {
  return STRINGS[language === "zh" ? "zh" : "en"];
}

/** "today", "tomorrow", "in 3 days" (localized), for due dates. */
export function relativeDay(iso: string | null, language: Language, now = Date.now()): string {
  if (!iso) return "";
  const days = Math.round((Date.parse(iso) - now) / 86_400_000);
  const format = new Intl.RelativeTimeFormat(language === "zh" ? "zh-CN" : "en", { numeric: "auto" });
  if (Math.abs(days) < 1) {
    const hours = Math.round((Date.parse(iso) - now) / 3_600_000);
    return Math.abs(hours) < 1 ? format.format(0, "day") : format.format(hours, "hour");
  }
  return format.format(days, "day");
}
