/**
 * Snapshot LeetCode's official study plans into packages/core so the profile
 * page never calls LeetCode at runtime. Re-run when LeetCode edits a plan:
 *   pnpm plans:sync
 */
import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const PLANS = ["top-interview-150", "leetcode-75", "top-100-liked", "dynamic-programming", "graph-theory", "binary-search"];
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), "../packages/core/src/study-plans.generated.ts");
const DIFFICULTY = { EASY: "Easy", MEDIUM: "Medium", HARD: "Hard" };

const QUERY = `query studyPlan($slug: String!) {
  studyPlanV2Detail(planSlug: $slug) {
    name
    slug
    planSubGroups { name questions { titleSlug title difficulty questionFrontendId } }
  }
}`;

async function fetchPlan(slug) {
  const res = await fetch("https://leetcode.com/graphql", {
    method: "POST",
    headers: { "content-type": "application/json", referer: "https://leetcode.com/" },
    body: JSON.stringify({ query: QUERY, variables: { slug } }),
  });
  if (!res.ok) throw new Error(`${slug}: HTTP ${res.status}`);
  const json = await res.json();
  const plan = json.data?.studyPlanV2Detail;
  if (!plan) throw new Error(`${slug}: ${JSON.stringify(json.errors ?? json)}`);
  return {
    slug: plan.slug,
    name: plan.name,
    // LeetCode keeps some groups with no questions; they can't be progressed.
    groups: plan.planSubGroups.filter((group) => group.questions.length > 0).map((group) => ({
      name: group.name,
      questions: group.questions.map((q) => {
        const difficulty = DIFFICULTY[q.difficulty];
        if (!difficulty) throw new Error(`${slug}: unknown difficulty ${q.difficulty}`);
        return { id: Number(q.questionFrontendId), slug: q.titleSlug, title: q.title, difficulty };
      }),
    })),
  };
}

const plans = [];
for (const slug of PLANS) {
  const plan = await fetchPlan(slug);
  const count = plan.groups.reduce((sum, group) => sum + group.questions.length, 0);
  console.log(`✓ ${plan.name}: ${count} questions in ${plan.groups.length} groups`);
  plans.push(plan);
}

// One question per line keeps plan edits readable in diffs.
const body = plans
  .map(
    (plan) => `  {
    slug: ${JSON.stringify(plan.slug)},
    name: ${JSON.stringify(plan.name)},
    groups: [
${plan.groups
  .map(
    (group) => `      {
        name: ${JSON.stringify(group.name)},
        questions: [
${group.questions.map((q) => `          ${JSON.stringify(q)},`).join("\n")}
        ],
      },`,
  )
  .join("\n")}
    ],
  },`,
  )
  .join("\n");

await writeFile(
  OUT,
  `// Generated by scripts/sync-study-plans.mjs from LeetCode's public study plans.
// Do not edit by hand; run \`pnpm plans:sync\` instead.
import type { StudyPlan } from "./study-plans";

export const STUDY_PLAN_DATA: readonly StudyPlan[] = [
${body}
];
`,
);
console.log(`wrote ${OUT}`);
